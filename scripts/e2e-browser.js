// Essai de bout en bout dans Chromium (Playwright) : voir « Développement » dans le README.
const { chromium } = require('playwright');
const fs = require('fs');
const f = process.argv[2];
(async () => {
  for (let i = 0; i < 300 && !fs.existsSync(f); i++) await new Promise(r => setTimeout(r, 200));
  const base = fs.readFileSync(f, 'utf8');
  console.log('adresse', base);
  const browser = await chromium.launch();
  const page = await browser.newPage();
  const errors = [];
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  page.on('pageerror', e => errors.push(String(e)));
  try {
    await page.goto(base);
    console.log('1.', page.url());
    await page.fill('input[name=password]', 'un mot de passe solide');
    await page.fill('input[name=password2]', 'un mot de passe solide');
    await page.fill('input[name=access_key_id]', 'AKIDADMIN');
    await page.fill('input[name=secret_access_key]', 'SECRET');
    await Promise.all([page.waitForNavigation(), page.click('form button')]);
    console.log('2. après setup', page.url(), (await page.textContent('body')).includes('Console configurée'));
    await page.fill('input[name=poste]', 'SRV01');
    await Promise.all([page.waitForNavigation(), page.click('table.import button')]);
    console.log('3. après import', page.url(), (await page.textContent('body')).includes('Bucket importé'));
    await page.waitForTimeout(1500);
    await page.goto(base);
    console.log('4. vue d\'ensemble', page.url(), await page.locator('h1').first().textContent());
    await page.screenshot({ path: f + '.png', fullPage: true });
    await Promise.all([page.waitForNavigation(), page.click('form[action="/lock"] button')]);
    console.log('5. après verrouillage', page.url());
    await page.fill('input[name=password]', 'un mot de passe solide');
    await Promise.all([page.waitForNavigation(), page.click('form button')]);
    console.log('6. après déverrouillage', page.url());
    await page.goto(base + 'settings');
    await page.fill('input[name=price]', '7,50');
    await Promise.all([page.waitForNavigation(), page.click('form[action="/settings"] button')]);
    console.log('7. réglages', (await page.textContent('body')).includes('Réglages enregistrés'));
    // Lot 2 : correction de la stratégie, clé du poste, paquet .kura.
    await page.goto(base + 'buckets/acme-srv01');
    await Promise.all([page.waitForNavigation(), page.click('text=Voir et appliquer la stratégie du modèle')]);
    const proposed = await page.textContent('pre.doc >> nth=1');
    console.log('8. aperçu stratégie', proposed.includes('SecureTransport') && !proposed.includes('kura-ctl-admin'));
    await page.fill('input[name=confirm]', 'acme-srv01');
    await Promise.all([page.waitForNavigation(), page.click('text=Appliquer chez Wasabi')]);
    console.log('9. stratégie appliquée', (await page.textContent('body')).includes('appliqué et vérifié par relecture'));
    await page.fill('form[action="/buckets/acme-srv01/cles"] input[name=confirm]', 'acme-srv01');
    await Promise.all([page.waitForNavigation(), page.click('text=Créer une clé et un paquet')]);
    const pw = (await page.textContent('strong.password')).trim();
    console.log('10. mot de passe affiché', /^[A-Z0-9]{4}(-[A-Z0-9]{4}){4}$/.test(pw));
    await page.screenshot({ path: f + '-paquet.png', fullPage: true });
    const [dl] = await Promise.all([page.waitForEvent('download'), page.click('a.button')]);
    const file = f + '.kura';
    await dl.saveAs(file);
    const pk = JSON.parse(fs.readFileSync(file, 'utf8'));
    console.log('11. paquet téléchargé', dl.suggestedFilename(), pk.format, !fs.readFileSync(file, 'utf8').includes('secret-poste'));
    await page.goto(base + 'buckets/acme-srv01');
    await page.fill('form[action$="/installee"] input[name=confirm]', 'acme-srv01');
    await Promise.all([page.waitForNavigation(), page.click('text=Confirmer l\'installation')]);
    // Le faux compte n'a jamais vu la clé servir : rien n'est désactivé.
    console.log('12. confirmation refusée sans preuve', (await page.textContent('body')).includes('jamais servi'));
    await page.goto(base + 'buckets/acme-srv01/corriger/strategie');
    console.log('13. stratégie à réappliquer', (await page.textContent('pre.doc >> nth=1')).includes('user/kura-acme-srv01'));
    await page.fill('input[name=confirm]', 'acme-srv01');
    await Promise.all([page.waitForNavigation(), page.click('text=Appliquer chez Wasabi')]);
    console.log('14. stratégie réappliquée', (await page.textContent('body')).includes('appliqué et vérifié par relecture'));
    await page.screenshot({ path: f + '-bucket.png', fullPage: true });
    fs.writeFileSync(f + '.pw', pw);
    // Lot 3 : configuration du poste, paquet d'installation complète, kit zip.
    await page.goto(base + 'buckets/acme-srv01');
    await Promise.all([page.waitForNavigation(), page.click('text=Préparer la configuration du poste')]);
    const yaml = await page.inputValue('textarea[name=yaml]');
    console.log('15. modèle de configuration', yaml.includes('bucket: acme-srv01') && yaml.includes('credential:hc-url'));
    await page.fill('textarea[name=yaml]', yaml.replace('url: credential:hc-url', 'url: https://hc-ping.com/en-clair'));
    await Promise.all([page.waitForNavigation(), page.click('text=Vérifier et enregistrer')]);
    console.log('16. URL en clair refusée', (await page.textContent('body')).includes('notify.report.url'));
    await page.fill('textarea[name=yaml]', yaml);
    await Promise.all([page.waitForNavigation(), page.click('text=Vérifier et enregistrer')]);
    console.log('17. configuration enregistrée', (await page.textContent('body')).includes('Configuration du poste enregistrée'));
    await page.fill('input[name=secret-hc-url]', 'https://hc-ping.example/uuid-e2e');
    await page.fill('form:has(input[name=secret-hc-url]) input[name=confirm]', 'acme-srv01');
    await Promise.all([page.waitForNavigation(), page.click('text=Créer une clé et le kit')]);
    const pw2 = (await page.textContent('strong.password')).trim();
    console.log('18. page du kit', /^[A-Z0-9]{4}(-[A-Z0-9]{4}){4}$/.test(pw2), (await page.textContent('body')).includes('install --package'));
    await page.screenshot({ path: f + '-kit.png', fullPage: true });
    const [kdl] = await Promise.all([page.waitForEvent('download'), page.click('text=Télécharger le kit')]);
    await kdl.saveAs(f + '.zip');
    const head = fs.readFileSync(f + '.zip').subarray(0, 2).toString();
    console.log('19. kit téléchargé', kdl.suggestedFilename(), head === 'PK');

    // Poste Ubuntu : modèle Linux, système choisi, kit avec le paquet .deb.
    await page.goto(base + '/buckets/acme-srv01/poste');
    await Promise.all([page.waitForNavigation(), page.click('text=Ubuntu 24.04 (amd64)')]);
    const lyaml = await page.inputValue('textarea[name=yaml]');
    console.log('20. modèle Ubuntu', lyaml.includes('source: /home/'), await page.inputValue('select[name=platform]'));
    await Promise.all([page.waitForNavigation(), page.click('text=Vérifier et enregistrer')]);
    console.log('21. configuration Ubuntu enregistrée', (await page.textContent('body')).includes('Ubuntu 24.04 (amd64)'));
    // Deux clés au plus chez Wasabi : la plus ancienne est désactivée puis supprimée.
    const old = 'form[action$="/cles/AKIDPOSTE0001/desactiver"]';
    await page.fill(old + ' input[name=confirm]', 'acme-srv01');
    await Promise.all([page.waitForNavigation(), page.click(old + ' button')]);
    const del = 'form[action$="/cles/AKIDPOSTE0001/supprimer"]';
    await page.fill(del + ' input[name=confirm]', 'acme-srv01');
    await Promise.all([page.waitForNavigation(), page.click(del + ' button')]);
    await page.fill('input[name=secret-hc-url]', 'https://hc-ping.example/uuid-e2e-linux');
    await page.fill('form:has(input[name=secret-hc-url]) input[name=confirm]', 'acme-srv01');
    await Promise.all([page.waitForNavigation(), page.click('text=Créer une clé et le kit')]);
    const lbody = await page.textContent('body');
    console.log('22. page du kit Ubuntu', lbody.includes('Sur le poste · Ubuntu 24.04 (amd64)'), lbody.includes('sudo apt install'), lbody.includes('sudo kura-agent install --package'), !lbody.includes('kura-agent.exe install'));
    await page.screenshot({ path: f + '-kit-ubuntu.png', fullPage: true });
    const [ldl] = await Promise.all([page.waitForEvent('download'), page.click('text=Télécharger le kit')]);
    await ldl.saveAs(f + '-ubuntu.zip');
    const lzip = fs.readFileSync(f + '-ubuntu.zip').toString('latin1');
    console.log('23. kit Ubuntu téléchargé', ldl.suggestedFilename(), lzip.includes('kura-agent_0.7.0_amd64.deb'), lzip.includes('awscli-exe-linux-x86_64.zip.sig'), !lzip.includes('AWSCLIV2.msi'));
  } catch (e) {
    console.log('ÉCHEC', e.message, page.url());
    console.log((await page.textContent('body')).slice(0, 400));
  }
  console.log('erreurs console :', errors);
  await browser.close();
  fs.writeFileSync(f + '.fin', '');
})();
